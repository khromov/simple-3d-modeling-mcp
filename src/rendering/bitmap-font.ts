const BITMAPS = new Map<string, boolean[][]>(
  Object.entries(GLYPHS).map(([ch, s]) => [ch, s.split("|").map((row) => [...row].map((c) => c === "#"))]),
);

export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function textWidth(text: string, scale: number): number {
  return text.length === 0 ? 0 : (text.length * (GLYPH_W + 1) - 1) * scale;
}

/**
 * Draws text into an interleaved pixel buffer (3 or 4 channels).
 * (x, y) is the top-left corner; pixels outside the buffer are clipped.
 */
export function drawText(
  buf: Uint8Array,
  width: number,
  height: number,
  channels: 3 | 4,
  x: number,
  y: number,
  text: string,
  scale: number,
  color: [number, number, number],
): void {
  let cx = Math.round(x);
  const top = Math.round(y);
  for (const ch of text.toUpperCase()) {
    const glyph = BITMAPS.get(ch) ?? BITMAPS.get("?")!;
    for (let gy = 0; gy < GLYPH_H; gy++) {
      for (let gx = 0; gx < GLYPH_W; gx++) {
        if (!glyph[gy][gx]) continue;
        for (let sy = 0; sy < scale; sy++) {
          const py = top + gy * scale + sy;
          if (py < 0 || py >= height) continue;
          for (let sx = 0; sx < scale; sx++) {
            const px = cx + gx * scale + sx;
            if (px < 0 || px >= width) continue;
            const i = (py * width + px) * channels;
            buf[i] = color[0];
            buf[i + 1] = color[1];
            buf[i + 2] = color[2];
          }
        }
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
}
